package tools

import "encoding/json"

// codeExecutionTools ports lib/ai/tools/code/{js,python}-run-tool.ts. Both
// have Execute == nil: neither TS tool defines an `execute`, so the AI SDK
// never runs them server-side -- the model's tool call streams straight to
// the client as a pending "input-available" part, and the frontend's
// already-live CodeExecutor (desktop/src/components/tool-invocation/
// code-executor.tsx, code.worker.ts) runs the code in-browser (QuickJS for
// JS, Pyodide for Python) and posts the result back via addToolResult. The
// chat loop (route.go) must stop generating the instant it sees a tool call
// with a nil Execute, for exactly this reason.
func codeExecutionTools() []Definition {
	return []Definition{
		{
			Name:    NameJavascriptExecution,
			Toolkit: ToolkitCode,
			Description: "Write and execute JavaScript code in the user's browser.\n" +
				"When users request code examples, use this tool to execute the code and show console.log " +
				"results rather than just providing static code.\n" +
				"For data generation or random operations, executing code to generate actual data is more " +
				"accurate than manually creating examples. This ensures users see real working results and " +
				"can trust the output is genuinely generated by the code logic.",
			ParametersSchema: json.RawMessage(`{
				"type": "object",
				"properties": {
					"code": {
						"type": "string",
						"description": "JavaScript code that will be executed in the user's browser. You can use await directly since the code runs in an async context (e.g., await fetch('https://api.example.com/data')).\n\nUse console.log, console.warn, and console.error to display execution results. Use \\n for line breaks to improve code readability for users.\n\nStandard JavaScript APIs are available (fetch, JSON, Math, Date, Array methods, etc.). DOM manipulation, localStorage, and other browser security-restricted features are not available."
					}
				},
				"required": ["code"]
			}`),
			Execute: nil,
		},
		{
			Name:    NamePythonExecution,
			Toolkit: ToolkitCode,
			Description: "Execute Python code in the user's browser via Pyodide. Use pyodide.http.open_url " +
				"for HTTP(S) downloads; CORS must allow the app origin.",
			ParametersSchema: json.RawMessage(`{
				"type": "object",
				"properties": {
					"code": {
						"type": "string",
						"description": "Execute Python code in the user's browser via Pyodide.\n\nNetwork access: use pyodide.http.open_url for HTTP/HTTPS, not urllib/request/requests. CORS must allow the app origin.\nExample (CSV):\nfrom pyodide.http import open_url\nimport pandas as pd\nurl = 'https://example.com/data.csv'\ndf = pd.read_csv(open_url(url))\nprint(df.head())\n\nOutput capture:\npyodide.setStdout({\n  batched: (output: string) => {\n    const type = output.startsWith('data:image/png;base64') ? 'image' : 'data'\n    logs.push({ type: 'log', args: [{ type, value: output }] })\n  },\n})\npyodide.setStderr({\n  batched: (output: string) => {\n    logs.push({ type: 'error', args: [{ type: 'data', value: output }] })\n  },\n})"
					}
				},
				"required": ["code"]
			}`),
			Execute: nil,
		},
	}
}
