package config

import (
	"fmt"
	"os"
	"reflect"
	"sort"
	"strconv"
	"strings"
	"time"
)

// EnvPrefix is what separates the test system's own variables from the
// AMIRO_* variables the application reads. Nothing under AMIRO_TEST_ ever
// reaches a spawned binary; harness/backend.Env() builds that set
// separately and is the only place that knows the app's names.
const EnvPrefix = "AMIRO_TEST_"

// EnvBinding is one configuration key and the environment variable that
// overrides it.
type EnvBinding struct {
	Path  string // dot path, e.g. "run.parallel"
	Name  string // AMIRO_TEST_RUN_PARALLEL
	Alias string // AMIRO_TEST_RUN_KEEP_ARTIFACTS, for camelCase keys; "" otherwise
	Kind  string // scalar kind, for `amirotest env --list`
}

// EnvBindings enumerates every overridable key, in tree order. Generated by
// reflection so it cannot drift from the struct.
func EnvBindings() []EnvBinding {
	var out []EnvBinding
	walkEnv(reflect.TypeOf(Config{}), "", &out)
	sort.SliceStable(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out
}

func walkEnv(typ reflect.Type, prefix string, out *[]EnvBinding) {
	for i := 0; i < typ.NumField(); i++ {
		f := typ.Field(i)
		path := joinPath(prefix, yamlName(f))
		switch f.Type.Kind() {
		case reflect.Struct:
			if f.Type == reflect.TypeOf(Duration(0)) {
				*out = append(*out, binding(path, "duration"))
				continue
			}
			walkEnv(f.Type, path, out)
		case reflect.Slice:
			// Lists of scalars are comma-separated. Lists of structs
			// (providers.llm) are not expressible as one variable and are
			// deliberately left to the file -- an environment variable
			// holding a serialised provider list would be a config format
			// inside a config format.
			if f.Type.Elem().Kind() == reflect.String {
				*out = append(*out, binding(path, "list"))
			}
		case reflect.Map:
			// backend.env has arbitrary keys; overriding the whole map from
			// one variable would mean inventing an escaping scheme.
		case reflect.String:
			*out = append(*out, binding(path, "string"))
		case reflect.Int, reflect.Int64:
			*out = append(*out, binding(path, "int"))
		case reflect.Bool:
			*out = append(*out, binding(path, "bool"))
		case reflect.Float64:
			*out = append(*out, binding(path, "float"))
		}
	}
}

func binding(path, kind string) EnvBinding {
	return EnvBinding{Path: path, Name: envName(path), Alias: envAlias(path), Kind: kind}
}

// envName is the mechanical mapping docs/testing/02-config.md specifies:
// dot-path uppercased, dots to underscores, prefixed.
//
//	run.parallel            -> AMIRO_TEST_RUN_PARALLEL
//	backend.database.driver -> AMIRO_TEST_BACKEND_DATABASE_DRIVER
func envName(path string) string {
	return EnvPrefix + strings.ToUpper(strings.ReplaceAll(path, ".", "_"))
}

// envAlias adds a word break at each camelCase hump, so run.keepArtifacts
// is reachable as AMIRO_TEST_RUN_KEEP_ARTIFACTS as well as by the
// mechanical AMIRO_TEST_RUN_KEEPARTIFACTS.
//
// Two names for one key is a cost. It is paid because the mechanical rule
// produces AMIRO_TEST_LOGGING_MAXBODYBYTES, which nobody types correctly on
// the first attempt, and a silently-ignored environment variable is the
// worst failure mode a config system has. The mechanical name wins if both
// are set, and `amirotest env --list` prints both.
func envAlias(path string) string {
	var b strings.Builder
	for _, r := range path {
		switch {
		case r == '.':
			b.WriteByte('_')
		case r >= 'A' && r <= 'Z':
			b.WriteByte('_')
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	alias := EnvPrefix + strings.ToUpper(b.String())
	if alias == envName(path) {
		return ""
	}
	return alias
}

// ApplyEnv overlays AMIRO_TEST_* variables onto cfg, returning the paths it
// changed (for run.json) and any parse failures as Problems.
func ApplyEnv(cfg *Config, lookup func(string) (string, bool)) (applied []string, problems []Problem) {
	if lookup == nil {
		lookup = os.LookupEnv
	}
	for _, b := range EnvBindings() {
		raw, ok := lookup(b.Name)
		name := b.Name
		if !ok && b.Alias != "" {
			raw, ok = lookup(b.Alias)
			name = b.Alias
		}
		if !ok {
			continue
		}
		if err := setByPath(cfg, b.Path, raw); err != nil {
			problems = append(problems, Problem{
				Key:     b.Path,
				Message: fmt.Sprintf("%s=%q: %v", name, raw, err),
			})
			continue
		}
		applied = append(applied, b.Path)
	}
	return applied, problems
}

// setByPath assigns a string value to a dot-addressed field.
func setByPath(cfg *Config, path, raw string) error {
	v := reflect.ValueOf(cfg).Elem()
	parts := strings.Split(path, ".")
	for i, part := range parts {
		typ := v.Type()
		field, ok := fieldByYAMLName(typ, part)
		if !ok {
			return fmt.Errorf("no such key %q", path)
		}
		v = v.FieldByIndex(field.Index)
		if i == len(parts)-1 {
			return assign(v, raw)
		}
		if v.Kind() != reflect.Struct {
			return fmt.Errorf("%q is not a section", strings.Join(parts[:i+1], "."))
		}
	}
	return nil
}

func assign(v reflect.Value, raw string) error {
	if v.Type() == reflect.TypeOf(Duration(0)) {
		d, err := time.ParseDuration(strings.TrimSpace(raw))
		if err != nil {
			return fmt.Errorf("not a duration (want 30m, 2m, 500ms)")
		}
		v.Set(reflect.ValueOf(Duration(d)))
		return nil
	}
	switch v.Kind() {
	case reflect.String:
		v.SetString(raw)
	case reflect.Bool:
		b, err := strconv.ParseBool(strings.TrimSpace(raw))
		if err != nil {
			return fmt.Errorf("not a boolean (want true or false)")
		}
		v.SetBool(b)
	case reflect.Int, reflect.Int64:
		n, err := strconv.ParseInt(strings.TrimSpace(raw), 10, 64)
		if err != nil {
			return fmt.Errorf("not an integer")
		}
		v.SetInt(n)
	case reflect.Float64:
		f, err := strconv.ParseFloat(strings.TrimSpace(raw), 64)
		if err != nil {
			return fmt.Errorf("not a number")
		}
		v.SetFloat(f)
	case reflect.Slice:
		if v.Type().Elem().Kind() != reflect.String {
			return fmt.Errorf("cannot be set from the environment")
		}
		v.Set(reflect.ValueOf(SplitList(raw)))
	default:
		return fmt.Errorf("cannot be set from the environment")
	}
	return nil
}

// SplitList parses a comma-separated list value. An empty string means an
// empty list -- AMIRO_TEST_RUN_TAGS_EXCLUDE= is how CI says "exclude
// nothing", and treating it as "leave the default alone" would make that
// impossible to express.
func SplitList(raw string) []string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return []string{}
	}
	parts := strings.Split(raw, ",")
	out := make([]string, 0, len(parts))
	for _, p := range parts {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}
