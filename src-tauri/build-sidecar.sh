#!/usr/bin/env bash
# Stages the Tauri "backend" sidecar slot (bundle.externalBin:
# ["binaries/backend"]) with a launcher for the Node adapter.
#
# History: this used to cross-compile backend-go/cmd/server into a native
# binary per rust target triple (Go's GOOS/GOARCH naming wanted translating to
# Rust's target-triple naming). The Go backend is gone; the replacement
# backend is adapter/src/server.mjs, a plain Node (>=22) HTTP server that
# serves the Next static export and bridges to the live jcode daemon.
#
# A Node script is not a native executable, so Tauri's externalBin contract
# (a binary sitting next to the app executable, found via sidecar("backend"))
# cannot be filled by it directly. What this script writes is a small
# executable launcher script in that slot that execs `node <adapter entry>`.
# Tauri's sidecar lookup and the Rust child-process lifecycle handling in
# src-tauri/src/lib.rs work exactly as before; only the file behind the slot
# changed.
#
# ============================================================================
# LIMITATION (honest, not a TODO): the launcher bakes in an absolute path to
# the adapter entry as it exists on THIS machine, and `node` must be on PATH
# at launch. That is fine for `tauri dev` and for running the built app from
# inside this checkout, but it is NOT a distributable desktop bundle: a
# shipped app has neither this repo path nor a guaranteed Node runtime. A real
# distribution needs the adapter packaged (e.g. as a Node SEA / single
# executable, or bundling a Node binary and adding it to externalBin). The Go
# binary was self-contained; this is the cost of the Node adapter and is
# tracked as a follow-up, not pretended away.
#
# Windows is not supported by this script: Tauri's externalBin requires a
# real .exe there, and a batch file cannot occupy that slot. See
# build-sidecar.ps1 for the explicit error.
# ============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
ADAPTER_ENTRY="$REPO_ROOT/adapter/src/server.mjs"
OUT_DIR="$SCRIPT_DIR/binaries"

if [ ! -f "$ADAPTER_ENTRY" ]; then
  echo "error: adapter entry not found at $ADAPTER_ENTRY" >&2
  echo "       the Node adapter (adapter/src/server.mjs) replaces backend-go; without it there is no backend." >&2
  exit 1
fi

if [ ! -d "$REPO_ROOT/adapter/node_modules/@1jehuang/jcode-sdk" ]; then
  echo "warning: adapter dependencies look uninstalled." >&2
  echo "         run: (cd adapter && pnpm install)   # or npm install" >&2
fi

if ! command -v node >/dev/null 2>&1; then
  echo "error: node not found on PATH -- the adapter is a Node server and cannot run without it." >&2
  exit 1
fi

TARGET_TRIPLE="${1:-$(rustc -Vv 2>/dev/null | awk '/^host:/ {print $2}')}"
if [ -z "$TARGET_TRIPLE" ]; then
  echo "error: could not determine rust target triple (rustc not on PATH?) -- pass one explicitly" >&2
  exit 1
fi

case "$TARGET_TRIPLE" in
  *-pc-windows-*)
    echo "error: Windows sidecar launchers are not supported (Tauri externalBin needs a real .exe; a Node script cannot fill it)." >&2
    echo "       Run the adapter directly instead: AMIRO_PORT=8787 node adapter/src/server.mjs" >&2
    exit 1
    ;;
esac

mkdir -p "$OUT_DIR"
OUT_FILE="$OUT_DIR/backend-${TARGET_TRIPLE}"

NODE_BIN="$(command -v node)"
cat > "$OUT_FILE" <<LAUNCHER
#!/usr/bin/env bash
# Generated by src-tauri/build-sidecar.sh -- do not edit by hand.
# Execs the Amiro Node adapter (replaces the old Go backend sidecar).
# The path below is absolute for THIS machine; see the script header for why a
# distributable build needs the adapter packaged differently.
exec "$NODE_BIN" "$ADAPTER_ENTRY" "\$@"
LAUNCHER
chmod +x "$OUT_FILE"

echo "staged backend sidecar launcher -> $OUT_FILE"
echo "  node:    $NODE_BIN"
echo "  adapter: $ADAPTER_ENTRY"
echo "note: development launcher only; packaging needs a Node runtime/SEA (see script header)."
