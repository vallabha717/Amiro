const NUM = /-?(?:\d+\.?\d*|\.\d+)(?:e[+-]?\d+)?/gi;
const SEGMENTS = /[MmLlHhVvCcSsQqTtAaZz][^MmLlHhVvCcSsQqTtAaZz]*/g;

export function pathBBox(d: string): BBox {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  let cx = 0;
  let cy = 0;

  const extend = (x: number, y: number) => {
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  };

  const segments = d.match(SEGMENTS) ?? [];
  for (const seg of segments) {
    const code = seg[0]!;
    const upper = code.toUpperCase();
    if (upper === "Z") {
      continue;
    }
    const relative = code !== upper;
    const nums = (seg.slice(1).match(NUM) ?? []).map(Number);

    if (upper === "H") {
      for (const n of nums) {
        cx = relative ? cx + n : n;
        extend(cx, cy);
      }
    } else if (upper === "V") {
      for (const n of nums) {
        cy = relative ? cy + n : n;
        extend(cx, cy);
      }
    } else if (upper === "A") {
      for (let i = 0; i + 7 <= nums.length; i += 7) {
        const ex = nums[i + 5]!;
        const ey = nums[i + 6]!;
        cx = relative ? cx + ex : ex;
        cy = relative ? cy + ey : ey;
        extend(cx, cy);
      }
    } else {
      const startX = cx;
      const startY = cy;
      for (let i = 0; i + 2 <= nums.length; i += 2) {
        const px = relative ? startX + nums[i]! : nums[i]!;
        const py = relative ? startY + nums[i + 1]! : nums[i + 1]!;
        extend(px, py);
        if (i + 2 >= nums.length - (nums.length % 2)) {
          cx = px;
          cy = py;
        }
      }
    }
  }

  if (minX === Infinity) {
    return { x: 0, y: 0, w: 0, h: 0 };
  }
  return { x: minX, y: minY, w: maxX - minX, h: maxY - minY };
}

export function unionBBox(boxes: BBox[]): BBox {
  if (boxes.length === 0) {
    return { x: 0, y: 0, w: 0, h: 0 };
  }
  const minX = Math.min(...boxes.map((b) => b.x));
  const minY = Math.min(...boxes.map((b) => b.y));
  const maxX = Math.max(...boxes.map((b) => b.x + b.w));
  const maxY = Math.max(...boxes.map((b) => b.y + b.h));
  return { x: minX, y: minY, w: maxX - minX, h: maxY - minY };
}
