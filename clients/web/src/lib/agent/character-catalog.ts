function pointStr(x: number, y: number): string {
  return `${dec2(x)} ${dec2(y)}`;
}

/** A filled circle expressed as four arcs (keeps bbox parsing exact). */
function circlePath(cx: number, cy: number, r: number): string {
  return (
    `M${pointStr(cx + r, cy)}` +
    `A${dec2(r)} ${dec2(r)} 0 0 1 ${pointStr(cx, cy + r)}` +
    `A${dec2(r)} ${dec2(r)} 0 0 1 ${pointStr(cx - r, cy)}` +
    `A${dec2(r)} ${dec2(r)} 0 0 1 ${pointStr(cx, cy - r)}` +
    `A${dec2(r)} ${dec2(r)} 0 0 1 ${pointStr(cx + r, cy)}Z`
  );
}

/** A hollow ring: the inner circle is reversed so the fill rule punches it out. */
function ringPath(
  cx: number,
  cy: number,
  outer: number,
  inner: number,
): string {
  const hole =
    `M${pointStr(cx + inner, cy)}` +
    `A${dec2(inner)} ${dec2(inner)} 0 0 0 ${pointStr(cx, cy + inner)}` +
    `A${dec2(inner)} ${dec2(inner)} 0 0 0 ${pointStr(cx - inner, cy)}` +
    `A${dec2(inner)} ${dec2(inner)} 0 0 0 ${pointStr(cx, cy - inner)}` +
    `A${dec2(inner)} ${dec2(inner)} 0 0 0 ${pointStr(cx + inner, cy)}Z`;
  return `${circlePath(cx, cy, outer)} ${hole}`;
}

/** A small four-point sparkle. */
function sparkPath(cx: number, cy: number, r: number): string {
  const k = r * 0.3;
  return (
    `M${pointStr(cx, cy - r)}` +
    `L${pointStr(cx + k, cy - k)}` +
    `L${pointStr(cx + r, cy)}` +
    `L${pointStr(cx + k, cy + k)}` +
    `L${pointStr(cx, cy + r)}` +
    `L${pointStr(cx - k, cy + k)}` +
    `L${pointStr(cx - r, cy)}` +
    `L${pointStr(cx - k, cy - k)}Z`
  );
}

/** A stroke-only mark that bends through a control point (brow, wink, blink). */
function curvePath(
  x1: number,
  y1: number,
  ctrlX: number,
  ctrlY: number,
  x2: number,
  y2: number,
): string {
  return `M${pointStr(x1, y1)}Q${pointStr(ctrlX, ctrlY)} ${pointStr(x2, y2)}`;
}

function barPath(x1: number, y1: number, x2: number, y2: number): string {
  return `M${pointStr(x1, y1)}L${pointStr(x2, y2)}`;
}

