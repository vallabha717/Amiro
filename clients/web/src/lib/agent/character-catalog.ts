const TAU = Math.PI * 2;
/** Straight up in SVG coordinates (y grows downward). */
const TOP = -Math.PI / 2;
/** Straight down in SVG coordinates. */
const BOTTOM = Math.PI / 2;

/** The single body viewBox every shape shares, so all bodies render 1:1. */
const BODY_VIEWBOX = 640;
/** How many samples the silhouette outline uses. */
const SILHOUETTE_SAMPLES = 56;
/** Lattice cells across the widest axis of a body (higher = finer dots). */
const LATTICE_DIVISIONS = 17;
/** Lattice dot radius as a fraction of the body's smaller half-extent. */
const LATTICE_DOT_RADIUS = 0.026;
/** Fraction of the half-viewBox a normalised body reaches. */
const FIELD_FIT = 0.94;

const dec = (value: number): number => Math.round(value * 10) / 10;
const dec2 = (value: number): number => Math.round(value * 100) / 100;

function clamp(value: number, lo: number, hi: number): number {
  return Math.max(lo, Math.min(hi, value));
}

/** Hermite smoothstep that also accepts a descending edge pair. */
function smoothstep(edge0: number, edge1: number, x: number): number {
  const t = clamp((x - edge0) / (edge1 - edge0), 0, 1);
  return t * t * (3 - 2 * t);
}

/** Wrap an angle difference into [-PI, PI]. */
function angleDelta(a: number, b: number): number {
  let d = (a - b) % TAU;
  if (d > Math.PI) d -= TAU;
  if (d < -Math.PI) d += TAU;
  return d;
}

/**
 * The smooth field: a radius multiplier around a circle. Harmonics give each
 * body its character (blob, cloud, star...), the optional lobe adds a sprout
 * stem, and the optional skirt ripples the bottom for a ghost hem.
 */
function fieldMultiplier(field: BodyField, theta: number): number {
  let m = 1;
  for (const harmonic of field.harmonics) {
    m += harmonic.amp * Math.cos(harmonic.n * theta + (harmonic.phase ?? 0));
  }
  if (field.lobe) {
    const d = angleDelta(theta, field.lobe.theta);
    m += field.lobe.amp * Math.exp(-(d * d) / (2 * field.lobe.spread ** 2));
  }
  if (field.skirt) {
    const d = angleDelta(theta, BOTTOM);
    const window = Math.exp(-(d * d) / (2 * field.skirt.spread ** 2));
    m += field.skirt.amp * Math.cos(field.skirt.count * theta) * window;
  }
  return m;
}

/** Peak of the field over a full turn, used to fit a shape inside its box. */
function fieldPeak(shape: BodyShapeDefinition): number {
  let peak = 0;
  for (let i = 0; i < 128; i += 1) {
    const theta = TOP + (i / 128) * TAU;
    peak = Math.max(peak, fieldMultiplier(shape.field, theta));
  }
  return Math.max(peak, 0.2);
}

function baseRadii(shape: BodyShapeDefinition): { rx: number; ry: number } {
  // Normalising by the field peak keeps every body inside the same viewBox,
  // so a star's tips and a blob's bulge both reach the frame edge.
  const half =
    (Math.min(shape.viewBox.width, shape.viewBox.height) / 2) * FIELD_FIT;
  const peak = fieldPeak(shape);
  return {
    rx: (half * (shape.field.rx ?? 0.95)) / peak,
    ry: (half * (shape.field.ry ?? 0.95)) / peak,
  };
}

/** Trace the field at its = 1 level into a smooth closed Bezier outline. */
function silhouettePath(shape: BodyShapeDefinition): string {
  const cx = shape.viewBox.width / 2;
  const cy = shape.viewBox.height / 2;
  const { rx, ry } = baseRadii(shape);
  const points: { x: number; y: number }[] = [];
  for (let i = 0; i < SILHOUETTE_SAMPLES; i += 1) {
    const theta = TOP + (i / SILHOUETTE_SAMPLES) * TAU;
    const m = fieldMultiplier(shape.field, theta);
    points.push({
      x: cx + Math.cos(theta) * rx * m,
      y: cy + Math.sin(theta) * ry * m,
    });
  }

  const n = points.length;
  const first = points[0]!;
  let d = `M${dec(first.x)} ${dec(first.y)}`;
  for (let i = 0; i < n; i += 1) {
    const a = points[i]!;
    const b = points[(i + 1) % n]!;
    const prev = points[(i - 1 + n) % n]!;
    const next = points[(i + 2) % n]!;
    // Catmull-Rom control points, expressed as cubic Beziers.
    const c1x = a.x + (b.x - prev.x) / 6;
    const c1y = a.y + (b.y - prev.y) / 6;
    const c2x = b.x - (next.x - a.x) / 6;
    const c2y = b.y - (next.y - a.y) / 6;
    d += `C${dec(c1x)} ${dec(c1y)} ${dec(c2x)} ${dec(c2y)} ${dec(b.x)} ${dec(b.y)}`;
  }
  return `${d}Z`;
}

/**
 * The dot lattice: a square grid of dots that only appear inside the field.
 * Radius and opacity follow the field (dense and bright near the middle, thin
 * and faint at the rim) plus a soft highlight, so the body reads as a lit orb
 * at hero size while the silhouette still carries it at 22px.
 */
export function bodyLattice(
  shape: BodyShapeDefinition,
  stride: number = 1,
): LatticeDot[] {
  const cx = shape.viewBox.width / 2;
  const cy = shape.viewBox.height / 2;
  const { rx, ry } = baseRadii(shape);
  const spacing =
    Math.min(shape.viewBox.width, shape.viewBox.height) / LATTICE_DIVISIONS;
  const cols = Math.ceil((rx * 1.15) / spacing);
  const rows = Math.ceil((ry * 1.15) / spacing);
  const dotBase =
    Math.min(shape.viewBox.width, shape.viewBox.height) * LATTICE_DOT_RADIUS;
  const highlight = { x: cx - rx * 0.34, y: cy - ry * 0.4 };
  const sigma = Math.min(rx, ry) * 0.55;
  // The dots must not run through the face: they are cleared out of an ellipse
  // around it and tapered at its edge, so the eyes always sit on a calm area
  // and stay readable at 22px, where the lattice collapses to a few dots.
  const face = shape.faceCenter;
  const faceClearX = rx * FACE_CLEARANCE_X;
  const faceClearY = ry * FACE_CLEARANCE_Y;
  const dots: LatticeDot[] = [];

  for (let iy = -rows; iy <= rows; iy += 1) {
    for (let ix = -cols; ix <= cols; ix += 1) {
      if (
        stride > 1 &&
        (Math.abs(ix) % stride !== 0 || Math.abs(iy) % stride !== 0)
      ) {
        continue;
      }
      const x = cx + ix * spacing;
      const y = cy + iy * spacing;
      const dx = (x - cx) / rx;
      const dy = (y - cy) / ry;
      const radius = Math.sqrt(dx * dx + dy * dy);
      const theta = Math.atan2(dy, dx);
      const limit = Math.max(fieldMultiplier(shape.field, theta), 0.2);
      const t = radius / limit;
      if (t > 1.04) {
        continue;
      }
      // 1 deep inside the field, 0 right at the rim.
      const inside = smoothstep(1.04, 0.72, t);
      const glow = Math.exp(
        -(
          ((x - highlight.x) ** 2 + (y - highlight.y) ** 2) /
          (2 * sigma * sigma)
        ),
      );
      const faceDistance = Math.hypot(
        (x - face.x) / faceClearX,
        (y - face.y) / faceClearY,
      );
      // 0 inside the face ellipse, 1 just outside it.
      const faceFade = smoothstep(0.82, 1.25, faceDistance);
      if (faceFade <= 0) {
        continue;
      }
      dots.push({
        cx: dec(x),
        cy: dec(y),
        r: dec(dotBase * (0.3 + 0.7 * inside) * (0.55 + 0.45 * faceFade)),
        opacity: dec2(
          clamp(
            (0.42 + 0.42 * inside + 0.16 * glow) * (0.35 + 0.65 * faceFade),
            0,
            0.95,
          ),
        ),
      });
    }
  }
  return dots;
}

/** Lattice density for a rendered size; small avatars need far fewer dots. */
export function latticeStrideForSize(size: number): number {
  if (size <= 34) return 3;
  if (size <= 110) return 2;
  return 1;
}

/** A few accent dots that the host component can slowly orbit around the body. */
export function bodyAccentDots(shape: BodyShapeDefinition): AccentDot[] {
  const cx = shape.viewBox.width / 2;
  const cy = shape.viewBox.height / 2;
  const { rx, ry } = baseRadii(shape);
  const base = Math.min(rx, ry);
  const specs = [
    { phase: -0.5, scale: 1.12 },
    { phase: 2.1, scale: 1.04 },
    { phase: 4.3, scale: 0.98 },
  ];
  return specs.map((spec, index) => ({
    cx: dec(cx + Math.cos(spec.phase) * base * spec.scale),
    cy: dec(cy + Math.sin(spec.phase) * base * spec.scale * 0.94),
    r: dec(base * 0.038 * (1.1 - index * 0.22)),
    center: { x: cx, y: cy },
    orbitRadius: dec(base * spec.scale),
    orbitSquash: 0.94,
    orbitPhase: spec.phase,
  }));
}

/** Keyframes for one accent dot's orbit, used by the host animation. */
export function accentOrbitKeyframes(
  dot: AccentDot,
  samples: number = 24,
): { cx: number[]; cy: number[] } {
  const cx: number[] = [];
  const cy: number[] = [];
  for (let i = 0; i <= samples; i += 1) {
    const angle = dot.orbitPhase + (i / samples) * TAU;
    cx.push(dec(dot.center.x + Math.cos(angle) * dot.orbitRadius));
    cy.push(
      dec(dot.center.y + Math.sin(angle) * dot.orbitRadius * dot.orbitSquash),
    );
  }
  return { cx, cy };
}

