/**
 * Agent character catalog.
 *
 * The Agent's visual language ("Aura Dots") is original to Amiro and is
 * *generated in code* rather than imported from any avatar set: every body is
 * a radial field (a smooth radius function built from a few cosine harmonics)
 * and is drawn as one silhouette path plus a lattice of dots whose radius and
 * opacity follow that same field. Nothing in this file is copied from a
 * third-party asset; see THIRD-PARTY-NOTICES.md.
 *
 * Public contract kept stable on purpose: the body ids, eye style ids, colour
 * ids, and every exported helper below are referenced by the saved identity
 * store, the sidebar/overview components, and the adapter tests. Only the
 * geometry behind those ids changed.
 */

/* -------------------------------------------------------------------------
   1. Types
   ------------------------------------------------------------------------- */

export interface BodyShapeDefinition {
  id: string;
  viewBox: { width: number; height: number };
  faceCenter: { x: number; y: number };
  /** Closed silhouette outline. Generated by `silhouettePath()`. */
  svgPath: string;
  /** Parameters of the radial field that shapes the silhouette and lattice. */
  field: BodyField;
}

/** A single cosine term added to the body radius: amp * cos(n * theta + phase). */
export interface BodyHarmonic {
  n: number;
  amp: number;
  phase?: number;
}

/** A localized radius bump, e.g. the sprout's stem. */
export interface BodyLobe {
  amp: number;
  theta: number;
  spread: number;
}

/** A ripple applied only near the bottom of a shape, e.g. the ghost's skirt. */
export interface BodySkirt {
  amp: number;
  count: number;
  spread: number;
}

export interface BodyField {
  harmonics: BodyHarmonic[];
  lobe?: BodyLobe;
  skirt?: BodySkirt;
  /** Horizontal / vertical radius as a fraction of half the viewBox. */
  rx?: number;
  ry?: number;
}

