function axisValue(values: Record<string, number>, id: string): number {
  const kebab = id.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
  const raw = values[id] ?? values[kebab] ?? PERSONALITY_AXIS_DEFAULT;
  return Number.isFinite(raw)
    ? Math.max(0, Math.min(100, Math.round(raw)))
    : PERSONALITY_AXIS_DEFAULT;
}

export function summarizePersonality(values: Record<string, number>): string {
  const DEAD_ZONE = 5;
  const leans: { text: string; mag: number }[] = [];
  let balancedCount = 0;

  for (const axis of PERSONALITY_AXES) {
    const val = axisValue(values, axis.id);
    const diff = val - 50;
    if (Math.abs(diff) <= DEAD_ZONE) {
      balancedCount++;
    } else {
      const mag = Math.abs(diff);
      const text =
        diff > 0 ? `${val}% ${axis.right}` : `${100 - val}% ${axis.left}`;
      leans.push({ text, mag });
    }
  }

  if (leans.length === 0) {
    return "Balanced across all five axes";
  }

  leans.sort((a, b) => b.mag - a.mag);
  const parts = leans.slice(0, 3).map((l) => l.text);
  if (balancedCount > 0 && parts.length <= 2) {
    parts.push("Balanced tone");
  }
  return parts.join(" · ");
}

